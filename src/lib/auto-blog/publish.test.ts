import { beforeEach, describe, expect, it, vi } from 'vitest';

const h = vi.hoisted(() => ({
  find: vi.fn(),
  exists: vi.fn(),
  create: vi.fn(),
  revalidatePath: vi.fn(),
  submitToIndexNow: vi.fn(),
  sendMessageToAdmin: vi.fn(),
}));

vi.mock('@/lib/mongodb', () => ({ default: vi.fn(async () => undefined) }));
vi.mock('@/models/Article', () => ({ default: { find: h.find, exists: h.exists, create: h.create } }));
vi.mock('next/cache', () => ({ revalidatePath: h.revalidatePath }));
vi.mock('@/lib/indexnow', () => ({ submitToIndexNow: h.submitToIndexNow }));
vi.mock('@/lib/telegram', () => ({ sendMessageToAdmin: h.sendMessageToAdmin }));

import { DuplicateTopicError, afterPublish, planNext, saveGenerated } from './publish';
import { makeArticle } from './test-fixtures';
import { MIN_INTERVAL_HOURS, type GeneratedArticle } from './types';

const HOUR = 3_600_000;
const NOW = Date.parse('2026-10-24T03:17:00Z');
const usedDocs = (docs: { topicKey?: string; category?: string; createdAt?: Date }[]) =>
  h.find.mockReturnValue({ select: () => ({ lean: async () => docs }) });

const article = (): GeneratedArticle => ({
  topicKey: 'hypertension',
  category: 'cardiology',
  languages: { ru: makeArticle('ru'), uz: makeArticle('uz'), kk: makeArticle('kk') },
  sources: [
    { name: 'MedlinePlus (NLM)', title: 'High Blood Pressure', url: 'https://medlineplus.gov/highbloodpressure.html', license: 'x' },
    { name: 'Europe PMC: J, 2024', title: 'Review', url: 'https://doi.org/10.1000/abc', license: 'y' },
  ],
});

beforeEach(() => {
  vi.clearAllMocks();
  h.submitToIndexNow.mockResolvedValue({ ok: true, submitted: 4, statuses: [200] });
  h.sendMessageToAdmin.mockResolvedValue(undefined);
});

describe('planNext', () => {
  it('is due right away when nothing was ever published, starting with the first category', async () => {
    usedDocs([]);
    const plan = await planNext({ now: NOW });
    expect(plan).toMatchObject({ due: true, hoursSinceLast: null, topic: { key: 'hypertension' } });
  });

  it('is not due before the interval has passed, and says when', async () => {
    usedDocs([{ topicKey: 'hypertension', category: 'cardiology', createdAt: new Date(NOW - 30 * HOUR) }]);
    const plan = await planNext({ now: NOW });
    expect(plan).toMatchObject({ due: false, reason: 'too-soon', nextInHours: MIN_INTERVAL_HOURS - 30 });
  });

  it('is due after 3 days, even if the cron fired a few minutes early (70 h, not 72)', async () => {
    usedDocs([{ topicKey: 'hypertension', category: 'cardiology', createdAt: new Date(NOW - 71 * HOUR) }]);
    const plan = await planNext({ now: NOW });
    expect(plan.due).toBe(true);
    // rotates away from the category that was just used
    expect(plan.due && plan.topic.category).toBe('neurology');
  });

  it('force ignores the interval', async () => {
    usedDocs([{ topicKey: 'hypertension', category: 'cardiology', createdAt: new Date(NOW - 1 * HOUR) }]);
    expect((await planNext({ now: NOW, force: true })).due).toBe(true);
  });

  it('honours skip, and ignores old articles without a topic key', async () => {
    usedDocs([{ createdAt: new Date(NOW - 100 * HOUR) }, { topicKey: undefined, category: 'general', createdAt: new Date(NOW - 99 * HOUR) }]);
    const plan = await planNext({ now: NOW, skip: ['hypertension'] });
    expect(plan.due && plan.topic.key).toBe('high-cholesterol');
  });

  it('reports when every topic is used', async () => {
    const { TOPICS } = await import('./topics');
    usedDocs(TOPICS.map((t, i) => ({ topicKey: t.key, category: t.category, createdAt: new Date(NOW - (500 + i) * HOUR) })));
    expect(await planNext({ now: NOW })).toMatchObject({ due: false, reason: 'topics-exhausted' });
  });
});

describe('saveGenerated', () => {
  it('stores every language side by side, flags it as an unreviewed AI article, and gives it no author', async () => {
    h.exists.mockResolvedValue(null);
    h.create.mockResolvedValue({});
    const published = await saveGenerated(article(), NOW);

    const doc = h.create.mock.calls[0][0];
    expect(doc).toMatchObject({ category: 'cardiology', topicKey: 'hypertension', autoGenerated: true, aiGenerated: true, isVerified: false });
    expect(doc).not.toHaveProperty('authorId');
    expect(Object.keys(doc.title).sort()).toEqual(['kk', 'ru', 'uz']);
    for (let i = 1; i <= 5; i++) {
      expect(doc[`section${i}_title`].ru).toBe(makeArticle('ru').sections[i - 1].title);
      expect(doc[`section${i}_content`].uz).toBe(makeArticle('uz').sections[i - 1].content);
      expect(doc[`section${i}_content`]).not.toHaveProperty('tg');
    }
    expect(doc.slug).toMatch(/^vysokoe-davlenie-[a-z0-9-]+-\d{5}$/);
    // The article page turns "<label> <url>" into a link in its Sources list
    expect(doc.references[0]).toBe('MedlinePlus (NLM): High Blood Pressure https://medlineplus.gov/highbloodpressure.html');

    expect(published.languages).toEqual(['ru', 'uz', 'kk']);
    expect(published.urls[0]).toBe(`https://www.duxtur.org/ru/blog/${doc.slug}`);
  });

  it('refuses a topic that already has an article, both by lookup and by the unique index', async () => {
    h.exists.mockResolvedValue({ _id: 1 });
    await expect(saveGenerated(article(), NOW)).rejects.toBeInstanceOf(DuplicateTopicError);
    expect(h.create).not.toHaveBeenCalled();

    h.exists.mockResolvedValue(null);
    h.create.mockRejectedValue(Object.assign(new Error('E11000'), { code: 11000, keyPattern: { topicKey: 1 } }));
    await expect(saveGenerated(article(), NOW)).rejects.toBeInstanceOf(DuplicateTopicError);
  });

  it('lets other database errors through', async () => {
    h.exists.mockResolvedValue(null);
    h.create.mockRejectedValue(new Error('connection lost'));
    await expect(saveGenerated(article(), NOW)).rejects.toThrow('connection lost');
  });
});

describe('afterPublish', () => {
  const published = { slug: 'x-12345', languages: ['ru', 'uz'], urls: ['https://www.duxtur.org/ru/blog/x-12345', 'https://www.duxtur.org/uz/blog/x-12345'] };

  it('refreshes the lists of the languages the article has, pings IndexNow and tells the admin', async () => {
    const r = await afterPublish(article(), published);
    expect(h.revalidatePath).toHaveBeenCalledWith('/ru/blog');
    expect(h.revalidatePath).toHaveBeenCalledWith('/uz/blog/c/cardiology');
    expect(h.revalidatePath).not.toHaveBeenCalledWith('/tg/blog');
    expect(h.submitToIndexNow).toHaveBeenCalledWith(expect.arrayContaining(published.urls));
    expect(h.sendMessageToAdmin.mock.calls[0][0]).toContain(makeArticle('ru').title);
    expect(r).toMatchObject({ revalidated: true, telegram: true });
  });

  it('never throws: the article is already saved, a failed ping must not fail the request', async () => {
    h.revalidatePath.mockImplementation(() => { throw new Error('cache down'); });
    h.submitToIndexNow.mockRejectedValue(new Error('bing down'));
    h.sendMessageToAdmin.mockRejectedValue(new Error('telegram down'));
    await expect(afterPublish(article(), published)).resolves.toMatchObject({ revalidated: false, telegram: false });
  });

  it('escapes HTML in the Telegram message (parse_mode is HTML)', async () => {
    const a = article();
    a.languages.ru = makeArticle('ru', { title: 'Давление <b>и</b> сосуды & сердце: что нужно знать' });
    await afterPublish(a, published);
    expect(h.sendMessageToAdmin.mock.calls[0][0]).toContain('Давление &lt;b&gt;и&lt;/b&gt; сосуды &amp; сердце');
  });
});
