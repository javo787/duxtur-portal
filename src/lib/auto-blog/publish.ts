import dbConnect from '@/lib/mongodb';
import Article from '@/models/Article';
import { articleSlug } from '@/lib/author-articles';
import { BASE_URL } from '@/lib/seo';
import { submitToIndexNow } from '@/lib/indexnow';
import { sendMessageToAdmin } from '@/lib/telegram';
import { revalidatePath } from 'next/cache';
import { pickTopic, type UsedTopic } from './topics';
import { LANGS, MIN_INTERVAL_HOURS, SECTION_COUNT, type GeneratedArticle, type Topic } from './types';

export class DuplicateTopicError extends Error {}

export type Plan =
  | { due: true; topic: Topic; hoursSinceLast: number | null }
  | { due: false; reason: 'too-soon' | 'topics-exhausted'; hoursSinceLast?: number; nextInHours?: number };

/** Is it time for the next article, and what should it be about. Read-only. */
export async function planNext(opts: { force?: boolean; skip?: string[]; now?: number } = {}): Promise<Plan> {
  await dbConnect();
  const now = opts.now ?? Date.now();

  const used = (await Article.find({ autoGenerated: true }).select('topicKey category createdAt').lean()) as unknown as {
    topicKey?: string;
    category?: string;
    createdAt?: Date;
  }[];

  const last = used.reduce<number | null>((max, a) => {
    const t = a.createdAt ? new Date(a.createdAt).getTime() : NaN;
    return Number.isFinite(t) && (max === null || t > max) ? t : max;
  }, null);
  const hoursSinceLast = last === null ? null : (now - last) / 3_600_000;

  if (!opts.force && hoursSinceLast !== null && hoursSinceLast < MIN_INTERVAL_HOURS) {
    return { due: false, reason: 'too-soon', hoursSinceLast, nextInHours: Math.ceil(MIN_INTERVAL_HOURS - hoursSinceLast) };
  }

  const usedTopics: UsedTopic[] = used
    .filter((a): a is { topicKey: string; category: string; createdAt: Date } => typeof a.topicKey === 'string' && !!a.category && !!a.createdAt)
    .map((a) => ({ topicKey: a.topicKey, category: a.category, at: a.createdAt }));

  const topic = pickTopic(usedTopics, opts.skip ?? []);
  if (!topic) return { due: false, reason: 'topics-exhausted', ...(hoursSinceLast !== null && { hoursSinceLast }) };
  return { due: true, topic, hoursSinceLast };
}

export interface Published {
  slug: string;
  languages: string[];
  urls: string[];
}

/** Saves a validated article. Throws DuplicateTopicError if the topic already has one. */
export async function saveGenerated(article: GeneratedArticle, now: number = Date.now()): Promise<Published> {
  await dbConnect();
  if (await Article.exists({ topicKey: article.topicKey })) throw new DuplicateTopicError(article.topicKey);

  const ru = article.languages.ru;
  if (!ru) throw new Error('Russian version is required');

  const doc: Record<string, unknown> = {
    slug: articleSlug(ru.title, now),
    category: article.category,
    topicKey: article.topicKey,
    autoGenerated: true,
    aiGenerated: true,
    isVerified: false,
    sources: article.sources,
    // The article page turns "<label> <url>" into a link in the "Sources" list.
    references: article.sources.map((s) => `${s.name}: ${s.title} ${s.url}`),
    title: {} as Record<string, string>,
    overview: {} as Record<string, string>,
  };
  for (let i = 1; i <= SECTION_COUNT; i++) {
    doc[`section${i}_title`] = {};
    doc[`section${i}_content`] = {};
  }
  const present = LANGS.filter((l) => article.languages[l]);
  for (const lang of present) {
    const a = article.languages[lang]!;
    (doc.title as Record<string, string>)[lang] = a.title;
    (doc.overview as Record<string, string>)[lang] = a.overview;
    a.sections.forEach((s, idx) => {
      (doc[`section${idx + 1}_title`] as Record<string, string>)[lang] = s.title;
      (doc[`section${idx + 1}_content`] as Record<string, string>)[lang] = s.content;
    });
  }

  try {
    await Article.create(doc);
  } catch (e) {
    const err = e as { code?: number; keyPattern?: Record<string, unknown> };
    if (err.code === 11000 && err.keyPattern && 'topicKey' in err.keyPattern) throw new DuplicateTopicError(article.topicKey);
    throw e;
  }

  const slug = doc.slug as string;
  return { slug, languages: present, urls: present.map((l) => `${BASE_URL}/${l}/blog/${slug}`) };
}

const escapeHtml = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/**
 * Everything that happens after the article is saved. None of it may fail the request: the article is
 * already live in the database, and a failed ping must not make the scheduler publish it a second time.
 */
export async function afterPublish(article: GeneratedArticle, published: Published): Promise<{ revalidated: boolean; indexNow: unknown; telegram: boolean }> {
  let revalidated = true;
  try {
    for (const lang of published.languages) {
      revalidatePath(`/${lang}`);
      revalidatePath(`/${lang}/blog`);
      revalidatePath(`/${lang}/blog/c/${article.category}`);
    }
    revalidatePath('/sitemap.xml');
  } catch (e) {
    revalidated = false;
    console.error('[AUTO-BLOG] revalidate failed', e);
  }

  let indexNow: unknown = null;
  try {
    indexNow = await submitToIndexNow([...published.urls, ...published.languages.map((l) => `${BASE_URL}/${l}/blog`)]);
  } catch (e) {
    console.error('[AUTO-BLOG] IndexNow failed', e);
  }

  let telegram = true;
  try {
    const ru = article.languages.ru!;
    await sendMessageToAdmin(
      `📰 <b>Новая автоматическая статья</b>\n${escapeHtml(ru.title)}\n\n` +
        `Языки: ${published.languages.join(', ')}\n${published.urls[0]}\n\n` +
        `⚠️ Материал подготовлен ИИ по открытым источникам, врач его не проверял. ` +
        `Если что-то не так — удалите статью или отметьте проверенной в админ-панели.`,
    );
  } catch (e) {
    telegram = false;
    console.error('[AUTO-BLOG] Telegram notice failed', e);
  }

  return { revalidated, indexNow, telegram };
}
